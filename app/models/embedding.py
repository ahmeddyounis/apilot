from datetime import datetime
from uuid import UUID

from pgvector.sqlalchemy import Vector
from sqlalchemy import ForeignKey, Index, Text, func
from sqlalchemy.dialects.postgresql import TIMESTAMP
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base

EMBEDDING_DIM = 384


class InvoiceEmbedding(Base):
    """Invoice-level embedding for near-duplicate search (separate table keeps hot
    invoice rows narrow and isolates the HNSW index)."""

    __tablename__ = "invoice_embeddings"

    # Migration 0004 creates this index with raw SQL (pgvector opclasses predate
    # Alembic's DDL helpers). It is declared here too so `alembic revision
    # --autogenerate` sees it in the metadata — otherwise every autogenerated
    # migration opens with a DROP of the index that makes near-duplicate search fast.
    __table_args__ = (
        # The near-duplicate search filters on model_name after the ANN scan; without
        # this it was a post-filter over whatever the vector index returned.
        Index("ix_invoice_embeddings_model_name", "model_name"),
        Index(
            "ix_invoice_embeddings_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    invoice_id: Mapped[UUID] = mapped_column(
        ForeignKey("invoices.id", ondelete="CASCADE"), primary_key=True
    )
    embedding: Mapped[list[float]] = mapped_column(Vector(EMBEDDING_DIM), nullable=False)
    model_name: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True), server_default=func.now(), nullable=False
    )
